/* Copies the four woff2 faces the page actually uses out of the vendored
   fontsource packages and writes the @font-face block that loads them.

   Self-hosted rather than CDN-linked: the CSP has no external font host, and a
   font that arrives from the same origin as the page is one fewer connection to
   open before the first paint.

   Run: node build/make-fonts.mjs */

import { copyFileSync, mkdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const out = join(root, "fonts");
mkdirSync(out, { recursive: true });

/* `standard` is the fontsource axis bundle that carries every axis except
   italic, which for Archivo means wght AND wdth. The wide display lockup needs
   wdth, so this is the file to ship rather than the wght-only one. */
const FACES = [
  {
    src: "fontsource-variable-archivo/files/archivo-latin-standard-normal.woff2",
    file: "archivo-variable.woff2",
    family: "Archivo Variable",
    weight: "100 900",
    stretch: "62% 125%",
  },
  {
    src: "fontsource-public-sans/files/public-sans-latin-400-normal.woff2",
    file: "public-sans-400.woff2",
    family: "Public Sans",
    weight: "400",
  },
  {
    src: "fontsource-public-sans/files/public-sans-latin-500-normal.woff2",
    file: "public-sans-500.woff2",
    family: "Public Sans",
    weight: "500",
  },
  {
    src: "fontsource-ibm-plex-mono/files/ibm-plex-mono-latin-400-normal.woff2",
    file: "plex-mono-400.woff2",
    family: "IBM Plex Mono",
    weight: "400",
  },
  {
    src: "fontsource-ibm-plex-mono/files/ibm-plex-mono-latin-500-normal.woff2",
    file: "plex-mono-500.woff2",
    family: "IBM Plex Mono",
    weight: "500",
  },
];

/* The latin subset covers every glyph on the page: country names come from
   world-countries in their English form, and the readout is digits and ASCII. */
const UNICODE_RANGE =
  "U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, " +
  "U+0304, U+0308, U+0329, U+2000-206F, U+2074, U+20AC, U+2122, U+2191, " +
  "U+2193, U+2212, U+2215, U+FEFF, U+FFFD";

const lines = [
  "/* Generated by build/make-fonts.mjs. Edit that script, not this file. */",
  "",
];
let total = 0;

for (const face of FACES) {
  const from = join(here, face.src);
  copyFileSync(from, join(out, face.file));
  total += statSync(from).size;
  lines.push(
    "@font-face {",
    `  font-family: "${face.family}";`,
    "  font-style: normal;",
    `  font-weight: ${face.weight};`,
    ...(face.stretch ? [`  font-stretch: ${face.stretch};`] : []),
    "  font-display: swap;",
    `  src: url("./${face.file}") format("woff2");`,
    `  unicode-range: ${UNICODE_RANGE};`,
    "}",
    "",
  );
}

writeFileSync(join(out, "fonts.css"), lines.join("\n"));
console.log(`fonts: ${FACES.length} faces, ${(total / 1024).toFixed(1)} KB total`);
