/* Build the globe's geography payload from Natural Earth 50m via world-atlas.
   Run: node build/make-geo.mjs

   Three artefacts land in data/, all committed so the deploy does no work:

     borders.bin    every country outline, as deduplicated TopoJSON arcs plus a
                    per-country index into them. Arcs are shared between
                    neighbours in the source, so storing arcs once rather than
                    rings per country roughly halves the payload and still lets
                    a single country light up on hover.
     idmap.bin      an equirectangular grid of country indices, run-length
                    encoded. Ocean is 0. This does two jobs: the dot field is
                    generated by sampling it (so the dots are real geography,
                    not scatter, and density stays a live control), and a click
                    resolves to a country in O(1) with no polygon tests.
     countries.json the fact table, joined from world-countries by ccn3.

   Coordinates ride the source topology's own integer quantization the whole
   way, so nothing is re-rounded and the wire format is just zigzag varints
   over deltas that were already delta encoded upstream. */

import { createRequire } from "node:module";
import { writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "data");

const topo = require("./world-atlas/countries-50m.json");
const topojson = require("./topojson-client/dist/topojson-client.js");
const facts = require("./world-countries/countries.json");

/* Grid resolution for the country index map. 0.2 degrees per cell keeps small
   nations (Luxembourg, Brunei, the Gulf states) several cells wide while the
   run-length encoding stays small, because ocean runs span whole rows. */
const W = 1800;
const H = 900;

/* ---------- varint buffer ---------- */

class ByteWriter {
  constructor() {
    this.buf = new Uint8Array(1 << 16);
    this.len = 0;
  }
  #room(n) {
    if (this.len + n <= this.buf.length) return;
    let size = this.buf.length;
    while (size < this.len + n) size *= 2;
    const next = new Uint8Array(size);
    next.set(this.buf.subarray(0, this.len));
    this.buf = next;
  }
  byte(v) {
    this.#room(1);
    this.buf[this.len++] = v & 0xff;
  }
  ascii(s) {
    for (let i = 0; i < s.length; i++) this.byte(s.charCodeAt(i));
  }
  f64(v) {
    this.#room(8);
    new DataView(this.buf.buffer).setFloat64(this.len, v, true);
    this.len += 8;
  }
  /** Unsigned LEB128. */
  uint(v) {
    let n = v >>> 0;
    while (n >= 0x80) {
      this.byte((n & 0x7f) | 0x80);
      n >>>= 7;
    }
    this.byte(n);
  }
  /** Zigzag then LEB128, so small negative deltas stay one byte. */
  int(v) {
    this.uint(v < 0 ? -v * 2 - 1 : v * 2);
  }
  done() {
    return this.buf.subarray(0, this.len);
  }
}

/* ---------- country table, joined to the topology ---------- */

const features = topojson.feature(topo, topo.objects.countries).features;
const byCcn3 = new Map(facts.map((f) => [f.ccn3, f]));
const byName = new Map(facts.map((f) => [f.name.common.toLowerCase(), f]));

/* Index 0 is ocean, so the table is one-based and a zero in the id map needs no
   special case at read time. */
const table = [null];
const indexOfGeometry = new Map();

features.forEach((feat, gi) => {
  const name = feat.properties?.name ?? "Unknown";
  const fact = byCcn3.get(String(feat.id)) ?? byName.get(name.toLowerCase());
  table.push({
    name: fact?.name.common ?? name,
    official: fact?.name.official ?? null,
    cca2: fact?.cca2 ?? null,
    cca3: fact?.cca3 ?? null,
    capital: fact?.capital?.[0] ?? null,
    region: fact?.region ?? null,
    subregion: fact?.subregion ?? null,
    area: fact?.area ?? null,
    landlocked: fact?.landlocked ?? null,
    languages: fact ? Object.values(fact.languages ?? {}).slice(0, 3) : [],
    currency: fact ? (Object.values(fact.currencies ?? {})[0]?.name ?? null) : null,
    borders: fact?.borders ?? [],
    latlng: fact?.latlng ?? null,
  });
  indexOfGeometry.set(gi, table.length - 1);
});

const matched = table.filter((c) => c && c.cca3).length;
console.log(`countries: ${table.length - 1} geometries, ${matched} joined to facts`);

/* ---------- borders.bin ---------- */

/* Which arcs belong to which country. TopoJSON stores a negative index for an
   arc traversed backwards; direction is irrelevant for drawing a line, so the
   sign is folded away and duplicates collapse. */
const arcsOfCountry = new Map();
const collect = (geom, set) => {
  if (typeof geom === "number") {
    set.add(geom < 0 ? ~geom : geom);
    return;
  }
  for (const part of geom) collect(part, set);
};

topo.objects.countries.geometries.forEach((geom, gi) => {
  const set = new Set();
  collect(geom.arcs ?? [], set);
  arcsOfCountry.set(indexOfGeometry.get(gi), [...set].sort((a, b) => a - b));
});

const bw = new ByteWriter();
bw.ascii("RE01");
bw.f64(topo.transform.scale[0]);
bw.f64(topo.transform.scale[1]);
bw.f64(topo.transform.translate[0]);
bw.f64(topo.transform.translate[1]);

let arcPoints = 0;
bw.uint(topo.arcs.length);
for (const arc of topo.arcs) {
  bw.uint(arc.length);
  arcPoints += arc.length;
  /* The source already stores position 0 absolute and the rest as deltas. */
  for (const [x, y] of arc) {
    bw.int(x);
    bw.int(y);
  }
}

bw.uint(table.length - 1);
for (let ci = 1; ci < table.length; ci++) {
  const list = arcsOfCountry.get(ci) ?? [];
  bw.uint(list.length);
  let prev = 0;
  for (const idx of list) {
    bw.int(idx - prev); /* ascending, so deltas are small */
    prev = idx;
  }
}

const borders = bw.done();
mkdirSync(out, { recursive: true });
writeFileSync(join(out, "borders.bin"), borders);
console.log(
  `borders.bin: ${(borders.length / 1024).toFixed(1)} KB, ` +
    `${topo.arcs.length} arcs, ${arcPoints} points`,
);

/* ---------- idmap.bin ---------- */

/* Scanline fill with an edge bucket per row. Even-odd across every ring of a
   feature at once, so holes (Lesotho inside South Africa, the Caspian) come out
   right without treating holes as a special case. */
const grid = new Uint16Array(W * H);

const lonToX = (lon) => ((lon + 180) / 360) * W;
const latToY = (lat) => ((90 - lat) / 180) * H;

/* Re-walk a ring so longitude runs continuously instead of jumping at the
   antimeridian. Russia, Fiji and the Aleutians all straddle it, and in raw
   -180..180 coordinates their two halves sort into a span that fills an entire
   row of the map. Unwrapped, the ring is a simple curve in a continuous frame
   (say 170..190) and the fill below wraps it back onto the cylinder. */
function unwrapRing(ring) {
  const out = new Array(ring.length);
  let lon = ring[0][0];
  out[0] = [lon, ring[0][1]];
  for (let i = 1; i < ring.length; i++) {
    let step = ring[i][0] - ring[i - 1][0];
    if (step > 180) step -= 360;
    else if (step < -180) step += 360;
    lon += step;
    out[i] = [lon, ring[i][1]];
  }
  return out;
}

const meanLon = (ring) => {
  let sum = 0;
  for (const [lon] of ring) sum += lon;
  return sum / ring.length;
};

/** Unwrap every ring of one polygon into a frame shared with its outer ring, so
    holes stay inside the shell they belong to. */
function unwrapPolygon(poly) {
  const outer = unwrapRing(poly[0]);
  const anchor = meanLon(outer);
  const rings = [outer];
  for (let i = 1; i < poly.length; i++) {
    const ring = unwrapRing(poly[i]);
    const shift = Math.round((anchor - meanLon(ring)) / 360) * 360;
    rings.push(shift ? ring.map(([lon, lat]) => [lon + shift, lat]) : ring);
  }
  return rings;
}

const wrapX = (x) => ((x % W) + W) % W;

function rasterize(rings, id) {
  const rows = new Map();
  let minRow = H;
  let maxRow = -1;

  for (const ring of rings) {
    for (let i = 0; i < ring.length - 1; i++) {
      const [lon1, lat1] = ring[i];
      const [lon2, lat2] = ring[i + 1];
      const y1 = latToY(lat1);
      const y2 = latToY(lat2);
      if (y1 === y2) continue;
      /* Rows whose centre falls inside the edge's vertical span. */
      const lo = Math.max(0, Math.ceil(Math.min(y1, y2) - 0.5));
      const hi = Math.min(H - 1, Math.ceil(Math.max(y1, y2) - 0.5) - 1);
      if (hi < lo) continue;
      const x1 = lonToX(lon1);
      const x2 = lonToX(lon2);
      for (let row = lo; row <= hi; row++) {
        let bucket = rows.get(row);
        if (!bucket) rows.set(row, (bucket = []));
        const t = (row + 0.5 - y1) / (y2 - y1);
        bucket.push(x1 + t * (x2 - x1));
      }
      if (lo < minRow) minRow = lo;
      if (hi > maxRow) maxRow = hi;
    }
  }

  for (let row = minRow; row <= maxRow; row++) {
    const xs = rows.get(row);
    if (!xs || xs.length < 2) continue;
    xs.sort((a, b) => a - b);
    const base = row * W;
    for (let k = 0; k + 1 < xs.length; k += 2) {
      const from = Math.ceil(xs[k] - 0.5);
      /* A ring that circles the globe (Antarctica) can span more than a full
         turn; one lap is all the row has. */
      const to = Math.min(from + W - 1, Math.ceil(xs[k + 1] - 0.5) - 1);
      for (let x = from; x <= to; x++) grid[base + wrapX(x)] = id;
    }
  }

  /* Stamp every vertex too. A scanline fill drops any island narrower than one
     cell, which would erase most of the Pacific and chunks of the Aegean. */
  for (const ring of rings) {
    for (const [lon, lat] of ring) {
      /* Except along the projection's clip line: Natural Earth closes
         Antarctica with a degenerate ring pinned at -89.999, and stamping it
         would draw a one-cell land strip across the whole bottom row. */
      if (lat <= -89.99) continue;
      const x = wrapX(Math.floor(lonToX(lon)));
      const y = Math.min(H - 1, Math.max(0, Math.floor(latToY(lat))));
      grid[y * W + x] = id;
    }
  }
}

/* Natural Earth clips Antarctica at the bottom of the projection, so the source
   has no polygon over the pole itself: sampling -89 returns ocean and the globe
   would render with a hole punched in its underside. Everything south of the
   Antarctic coast is Antarctica, so extend each column from its southernmost
   coastal cell down to the pole. Working from the southernmost cell rather than
   the northernmost means offshore islands stay islands instead of smearing a
   land bridge back to the mainland. */
function capSouthPole(id) {
  const from = Math.floor(((90 - -60) / 180) * H); /* nothing else lives here */
  let filled = 0;
  for (let x = 0; x < W; x++) {
    let southmost = -1;
    for (let y = H - 1; y >= from; y--) {
      if (grid[y * W + x] === id) {
        southmost = y;
        break;
      }
    }
    if (southmost < 0) continue;
    for (let y = southmost; y < H; y++) {
      if (grid[y * W + x] === 0) {
        grid[y * W + x] = id;
        filled++;
      }
    }
  }
  return filled;
}

features.forEach((feat, gi) => {
  const id = indexOfGeometry.get(gi);
  const geom = feat.geometry;
  if (!geom) return;
  const polys = geom.type === "Polygon" ? [geom.coordinates] : geom.coordinates;
  for (const poly of polys) rasterize(unwrapPolygon(poly), id);
});

const antarctica = table.findIndex((c) => c && c.name === "Antarctica");
if (antarctica > 0) {
  console.log(`antarctic cap: filled ${capSouthPole(antarctica)} cells`);
}

const iw = new ByteWriter();
iw.ascii("RE02");
iw.uint(W);
iw.uint(H);
let runs = 0;
let land = 0;
for (let i = 0; i < grid.length; ) {
  const id = grid[i];
  let j = i + 1;
  while (j < grid.length && grid[j] === id) j++;
  iw.uint(id);
  iw.uint(j - i);
  if (id !== 0) land += j - i;
  runs++;
  i = j;
}
const idmap = iw.done();
writeFileSync(join(out, "idmap.bin"), idmap);
console.log(
  `idmap.bin: ${(idmap.length / 1024).toFixed(1)} KB, ${W}x${H}, ` +
    `${runs} runs, land ${((land / grid.length) * 100).toFixed(1)}%`,
);

/* ---------- countries.json ---------- */

const json = JSON.stringify(table);
writeFileSync(join(out, "countries.json"), json);
console.log(`countries.json: ${(json.length / 1024).toFixed(1)} KB`);
