/* Emits the Cloudflare Pages `_headers` file from vercel.json.

   The headers exist in two dialects because the site is deployed to two hosts,
   but they are only ever written once. vercel.json stays the source; this
   translates it. Hand-editing _headers is how a CSP silently drifts on one host
   and ships a blank page there while the other host looks fine.

   The translation is not a syntax swap, because the two hosts disagree about
   what to do when several rules match one file. Vercel takes the last match and
   drops the rest. Cloudflare concatenates them, so sw.js, which matches both
   `/(.*).(js)` and `/sw.js`, came back with two Cache-Control values joined by a
   comma. Browsers read the first max-age in that list, so the service worker
   would have been held for an hour on Cloudflare while Vercel revalidated it
   every time. To keep the hosts honest we resolve the rules ourselves against
   the real file list and emit one unambiguous block per file, so nothing on
   Cloudflare ever matches twice.

   Run: node build/make-headers.mjs        writes _headers
        node build/make-headers.mjs --list prints the deployable file list */

import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, relative } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const config = JSON.parse(readFileSync(join(root, "vercel.json")));

/* What the site is, as opposed to what the repo holds. The build scripts, the
   tests, the editor config and the README are all inputs to the site rather than
   part of it, and Cloudflare would serve every one of them as a public asset. */
const SKIP = new Set(["build", "test", "node_modules", ".git", ".vercel", ".claude"]);
const SKIP_FILES = new Set([
  "vercel.json", "jsconfig.json", "project.config.json", "README.md", "_headers",
]);

function runtimeFiles(dir = root) {
  return readdirSync(dir).flatMap((name) => {
    if (name.startsWith(".") || SKIP.has(name)) return [];
    const full = join(dir, name);
    if (statSync(full).isDirectory()) return runtimeFiles(full);
    if (dir === root && SKIP_FILES.has(name)) return [];
    return [relative(root, full)];
  });
}

const files = runtimeFiles().sort();

if (process.argv.includes("--list")) {
  console.log(files.join("\n"));
  process.exit(0);
}

/* Vercel writes path-to-regexp, so turn each source into something we can test a
   real path against. Two shapes appear in our config: a `(.*)` catch-all and an
   extension alternation like `(js|css|svg)`. */
function toMatcher(source) {
  const pattern = source
    .replace(/[.]/g, "\\.")
    .replace(/\(\\\.\*\)/g, ".*")
    .replace(/\\\.\(([a-z|]+)\)/g, "\\.($1)");
  return new RegExp(`^${pattern}$`);
}

const rules = config.headers.map((rule) => ({
  match: toMatcher(rule.source),
  headers: rule.headers,
}));

/* Vercel's own resolution: every matching rule applies, later wins on conflict. */
function resolve(path) {
  const out = new Map();
  for (const rule of rules) {
    if (!rule.match.test(path)) continue;
    for (const { key, value } of rule.headers) out.set(key, value);
  }
  return out;
}

/* index.html is reachable at both `/` and its own name, and cleanUrls means the
   bare path is the one people get, so both need the same answer. */
const paths = files.map((f) => `/${f}`);
paths.push("/");

const resolved = new Map(paths.map((p) => [p, resolve(p)]));

/* Anything identical everywhere belongs in one `/*` block. In practice that is
   the security set, which no path overrides. Keeping it factored out is what
   stops the CSP from being repeated once per file and blowing the size limit. */
const universal = new Map();
const [first, ...rest] = paths;
for (const [key, value] of resolved.get(first)) {
  if (rest.every((p) => resolved.get(p).get(key) === value)) universal.set(key, value);
}

const blocks = [];
blocks.push(
  ["/*", ...[...universal].map(([k, v]) => `  ${k}: ${v}`)].join("\n"),
);
for (const path of paths) {
  const specific = [...resolved.get(path)].filter(([k]) => !universal.has(k));
  if (!specific.length) continue;
  blocks.push([path, ...specific.map(([k, v]) => `  ${k}: ${v}`)].join("\n"));
}

const output = `# Generated by build/make-headers.mjs from vercel.json. Do not edit.\n\n${blocks.join("\n\n")}\n`;
writeFileSync(join(root, "_headers"), output);
console.log(`wrote _headers: ${blocks.length} rules over ${files.length} files`);
